package com.music.bitchord.data

import com.music.bitchord.data.model.BrowseItem
import com.music.bitchord.data.model.SearchResult
import com.music.bitchord.data.model.ShelfItem
import com.music.bitchord.data.model.Song
import kotlin.jvm.JvmName

/**
 * Filter and detection engine for AI-generated music and synthetic content.
 * Identifies songs, covers, generators (Suno, Udio, AI vocals, Diff-SVC, RVC, etc.)
 * to allow users to completely hide and block AI-generated tracks from browsing and playback.
 */
object AiContentFilter {

    private val AI_KEYWORDS_REGEX = Regex(
        "(?i)\\b(suno(\\s*ai)?|udio(\\s*ai)?|stable\\s*audio|musiclm|musicfx|diff-svc|rvc(\\s*v[0-9]+)?|weights\\.gg|elevenlabs)\\b|" +
        "(?i)\\b(ai|ia)\\s*[-_]?\\s*(cover|version|remake|song|music|musique|track|vocals?|voice|voix|parody|parodie|gen|generation|clone|clonage)\\b|" +
        "(?i)\\b(cover|version|remake|chanson|musique|voix|morceau)\\s*[-_]?\\s*(ai|ia)\\b|" +
        "(?i)\\b(g[eé]n[eé]r[eé](e)?|fait(e)?|cr[eé][eé](e)?)\\s+par\\s+(une\\s+|l')?(ia|ai)\\b|" +
        "(?i)\\b(ai|ia)\\s*[-_]?\\s*generated\\b|" +
        "(?i)\\[(ai|ia)\\s*(cover|version)?\\]|\\((ai|ia)\\s*(cover|version)?\\)|" +
        "(?i)\\bfeat\\.?\\s+(ai|ia)\\b"
    )

    /**
     * Checks if a given text contains typical AI generation tags, prompts, or markers.
     */
    fun isAiText(text: String?): Boolean {
        if (text.isNullOrBlank()) return false
        return AI_KEYWORDS_REGEX.containsMatchIn(text)
    }

    /**
     * True if this Song appears to be generated by AI, an AI cover, or an AI vocal clone.
     */
    fun isAiSong(song: Song): Boolean {
        if (isAiText(song.title)) return true
        if (isAiText(song.artist)) return true
        if (isAiText(song.albumName)) return true
        return false
    }

    /**
     * True if this ShelfItem appears to be an AI-generated song, album, or playlist.
     */
    fun isAiShelfItem(item: ShelfItem): Boolean {
        if (isAiText(item.title)) return true
        if (isAiText(item.subtitle)) return true
        return false
    }

    /**
     * True if this BrowseItem appears to be an AI-generated item.
     */
    fun isAiBrowseItem(item: BrowseItem): Boolean {
        if (isAiText(item.title)) return true
        if (isAiText(item.subtitle)) return true
        return false
    }

    /**
     * True if this SearchResult matches AI-generated patterns.
     */
    fun isAiSearchResult(result: SearchResult): Boolean {
        return when (result) {
            is SearchResult.TopTrack -> isAiSong(result.song)
            is SearchResult.Track -> isAiSong(result.song)
            is SearchResult.Browse -> isAiBrowseItem(result.item)
        }
    }
}

// Extension helpers
fun Song.isAiGenerated(): Boolean = AiContentFilter.isAiSong(this)
fun ShelfItem.isAiGenerated(): Boolean = AiContentFilter.isAiShelfItem(this)
fun BrowseItem.isAiGenerated(): Boolean = AiContentFilter.isAiBrowseItem(this)
fun SearchResult.isAiGenerated(): Boolean = AiContentFilter.isAiSearchResult(this)

@JvmName("filterAiSongs")
fun List<Song>.filterAiSongs(): List<Song> = filterNot { it.isAiGenerated() }

@JvmName("filterAiShelfItems")
fun List<ShelfItem>.filterAiShelfItems(): List<ShelfItem> = filterNot { it.isAiGenerated() }

@JvmName("filterAiSearchResults")
fun List<SearchResult>.filterAiSearchResults(): List<SearchResult> = filterNot { it.isAiGenerated() }
